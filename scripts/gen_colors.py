#!/usr/bin/env python3
"""Generate colors/defaults.xml from design/tokens.json.

Do NOT hand-edit the generated colors/defaults.xml; edit tokens.json and re-run this script.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOKENS = ROOT / "design" / "tokens.json"
OUT = ROOT / "colors" / "defaults.xml"


def resolve_base(name_or_hex: str, colors: dict) -> str:
    """Resolve a base color token name to its bare RRGGBB hex, or pass through literal hex."""
    if name_or_hex in colors:
        return colors[name_or_hex]
    return name_or_hex


def main() -> int:
    data = json.loads(TOKENS.read_text(encoding="utf-8"))
    colors: dict[str, str] = data["colors"]
    alpha_helpers: dict[str, dict] = data["alpha_helpers"]

    lines = [
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
        "<!-- GENERATED by scripts/gen_colors.py from design/tokens.json. Do not hand-edit. -->",
        "<colors>",
    ]

    for name, hexval in colors.items():
        if len(hexval) != 6:
            print(f"error: color {name} must be 6 hex digits (RRGGBB), got {hexval!r}", file=sys.stderr)
            return 1
        lines.append(f'    <color name="{name}">FF{hexval.upper()}</color>')

    lines.append("")
    for name, spec in alpha_helpers.items():
        base_hex = resolve_base(spec["base"], colors)
        alpha = spec["alpha"].upper()
        lines.append(f'    <color name="{name}">{alpha}{base_hex.upper()}</color>')

    lines.append("</colors>")
    lines.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(colors)} base colors, {len(alpha_helpers)} alpha helpers)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
